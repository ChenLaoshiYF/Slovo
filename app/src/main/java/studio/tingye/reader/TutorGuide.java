package studio.tingye.reader;

/** Reviewed learning cards ground common beginner requests before small-model generation. */
final class TutorGuide {
  static String answer(String role,String input) {
    String message=Lexicon.key(input);
    if(message.matches(".*я\\s+учиться.*") || message.matches(".*я\\s+учусь\\s+русский.*"))
      return "Я студент, и я учу русский язык.\n我是学生，我在学俄语。\n这里用 я учу русский язык，或 я учусь русскому языку。\nА где ты учишься?";
    if(has(message,"不会俄语","不会说","不太会俄语","听不懂","не понимаю","не говорю"))
      return "Я пока плохо говорю по-русски. Говорите, пожалуйста, медленнее.\n我现在俄语说得还不好，请您说慢一点。\nДавай попробуем вместе?";
    if(has(message,"谢谢","спасибо"))return "Пожалуйста! Рад помочь.\n不客气，很高兴帮上忙。\nЧто ещё хочешь попробовать сказать по-русски?";
    if(has(message,"天气","погода"))return "Какая сегодня погода? Сегодня солнечно.\n今天天气怎么样？今天晴朗。\nА какая погода у тебя?";
    if(has(message,"занимает","занимать"))return "Этот стол занимает много места.\n这张桌子很占地方。занимает 是 занимать 的第三人称单数形式。表示占用空间或时间时，后面接第四格。\nА что занимает много времени у тебя?";
    if(has(message,"不想","不要去","не хочу"))return "";
    switch(role) {
      case "CAFE":
        if(has(message,"不加糖","无糖","без сахара"))
          return "Мне, пожалуйста, кофе без сахара.\n请给我一杯不加糖的咖啡。без сахара 中 сахара 用第二格。\nВы будете пить кофе здесь или возьмёте с собой?\n您在这里喝，还是打包带走？";
        if(has(message,"多少钱","сколько","价钱"))return "Сколько стоит чашка кофе?\n一杯咖啡多少钱？\nВы хотите большой кофе или маленький?";
        if(has(message,"牛奶","молоко"))return "Мне кофе с молоком, пожалуйста.\n请给我一杯加奶咖啡。с молоком 是 с 加第五格。\nА сахар нужен?";
        if(has(message,"茶","чай"))return "Мне, пожалуйста, чашку чая.\n请给我一杯茶。чашку 在这里是第四格。\nЧёрный или зелёный чай?";
        if(has(message,"咖啡","кофе"))return "Мне, пожалуйста, чашку кофе.\n请给我一杯咖啡。\nВы будете пить здесь?";
        break;
      case "STATION":
        if(has(message,"莫斯科","москв"))return has(message,"明天","завтра")
            ?"Мне нужен билет до Москвы на завтра.\n我需要一张明天去莫斯科的票。до Москвы 是 до 加第二格。\nВам билет в одну сторону или туда и обратно?\n您要单程还是往返票？"
            :"Мне нужен билет до Москвы.\n我需要一张去莫斯科的票。до Москвы 是 до 加第二格。\nНа какую дату вам нужен билет?\n您需要哪一天的票？";
        if(has(message,"明天","завтра"))return "Я хочу поехать завтра.\n我想明天出发。\nКуда вы хотите поехать?";
        if(has(message,"多少","сколько"))return "Сколько стоит билет?\n车票多少钱？\nНа какую дату вам нужен билет?";
        if(has(message,"几点","когда","时间"))return "Во сколько отправляется поезд?\n火车几点出发？\nВам удобнее утром или вечером?";
        break;
      case "STUDENT":
        if(has(message,"电子","электро"))return "Я изучаю электронику.\n我学电子学。изучаю 后的 электронику 是第四格。\nПочему ты выбрал эту специальность?\n你为什么选这个专业？";
        if(has(message,"大学","университет"))return "Я учусь в университете.\n我在大学读书。в университете 是第六格。\nНа каком факультете ты учишься?";
        if(has(message,"爱好","喜欢","хобби","люблю"))return "В свободное время я люблю слушать музыку.\n空闲时我喜欢听音乐。\nА что ты любишь делать?";
        break;
      case "TUTOR":
        if(has(message,"介绍","名字","自我","зовут"))return "Меня зовут Чэнь. Я студент. Я учу русский язык.\n我姓陈，是学生，正在学俄语。把 Чэнь 换成自己的名字就可以。\nА как тебя зовут?";
        if(has(message,"学习","учить"))return "Я учу русский язык каждый день.\n我每天都学俄语。учить 强调学习具体内容。\nПочему ты учишь русский язык?";
        break;
      default:break;
    }
    return "";
  }
  private static boolean has(String input,String... words) {
    for(String word:words)if(input.contains(word))return true;return false;
  }
}
